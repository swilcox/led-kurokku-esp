/// Render a string into a column-based byte buffer.
/// Each byte is one column (bit 0 = top row).
/// Characters are separated by 1 blank column.
pub fn render_text(s: &str) -> Vec<u8> {
    let chars: Vec<char> = s.chars().collect();
    let mut buf = Vec::new();
    for (i, &ch) in chars.iter().enumerate() {
        let g = glyph(ch);
        buf.extend_from_slice(&g);
        if i < chars.len() - 1 {
            buf.push(0x00); // 1-column gap
        }
    }
    buf
}

