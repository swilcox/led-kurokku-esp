/// 5x7 bitmap font. Each glyph is 5 columns; each byte is one column,
/// bit 0 = top row, bit 6 = bottom row.
///
/// ASCII ported from led-kurokku-go/font/font5x7.go. Katakana (U+30A1–U+30FC)
/// added locally. Dakuten/handakuten kana (ガ, パ, ...) render as their
/// unvoiced base — there's no room for the mark in a 5×7 cell.
type Glyph = [u8; 5];

/// Get the glyph for a character. Returns '?' glyph for unknown chars.
pub fn glyph(ch: char) -> Glyph {
    let idx = ch as u32;
    if idx >= 32 && idx <= 126 {
        FONT5X7[(idx - 32) as usize]
    } else if ch == '°' {
        DEGREE_GLYPH
    } else if let Some(g) = katakana_glyph(ch) {
        g
    } else {
        // '?' fallback
        FONT5X7[('?' as u32 - 32) as usize]
    }
}

